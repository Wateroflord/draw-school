import 'shapes.dart';

/// Страница теории: текст и иллюстрация.
class Page {
  final String text;
  final List<G> art;
  const Page(this.text, [this.art = const []]);
}

/// Упражнение: обвести подсказку (trace) или свободно повторить за отведённое время.
class Exercise {
  final String task;
  final List<G> guide;
  final int seconds; // 0 — без таймера
  final bool trace; // показывать подсказку под рукой и оценивать точность
  const Exercise(this.task, this.guide, {this.seconds = 0, this.trace = true});
}

class Lesson {
  final String id, title, about;
  final List<Page> pages;
  final List<Exercise> exercises;
  const Lesson(this.id, this.title, this.about, this.pages, this.exercises);
}

class Module {
  final String title, emoji;
  final List<Lesson> lessons;
  const Module(this.title, this.emoji, this.lessons);
}

